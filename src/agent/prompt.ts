/** T73：基础层与专用指令之间的作用域声明。
 *  「不污染」的核心：基础层管「怎么做事」（工具纪律、事实纪律、记忆检索、安全边界），
 *  格式与内容以专用指令为准——否则 18k 字主提示词会把「只输出 JSON」「只回 PASS/FAIL」
 *  这类严格输出契约冲散。声明放在专用指令之前，专用指令仍是最后一段（优先级最高）。 */
export const SCOPE_NOTE = `## 本次调用：基础层的作用边界
上文的基础行为规范是长期规范，负责你**怎么做事**：工具使用纪律、事实与来源纪律、记忆与检索规则、安全与隐私边界、默认回答风格。
**本次调用的输出内容与格式，以紧随其后的专用指令为准**；基础层中关于回答形态、篇幅、语气、格式的条款，在本次调用中一律让位于专用指令。
专用指令要求严格输出格式时（只输出 JSON、只回 PASS 或 FAIL、只输出摘要正文等）：严格遵守它，不要附加解释、前言、问候或补充说明。
要求输出 JSON 时，直接输出裸 JSON——第一个字符就是左花括号，不要用代码块记号包裹，不要写成「好的，结果如下」再给内容。要求只回 PASS 或 FAIL 时，就只回那一个词或那一行。`

/** T73：统一 system 拼接入口（loop.ts 与 hooks/vision/压缩等内部调用共用）。
 *  顺序即优先级：越靠后越优先。主提示词永远作为基础层注入，任何调用都不例外。 */
export function composeSystem(p: {
  /** 环境注入（~/.yyagent/injections 返回的内容） */
  injection?: string
  /** 技能工作流文档 */
  skills?: string
  /** 专用角色/任务指令——放最末，优先级最高；存在时会先插入作用域声明 */
  role?: string
  /** 追加段（如环境扫描 envScan、记忆指引） */
  suffix?: string
}): string {
  const layers: string[] = [SYSTEM_PROMPT]
  if (p.injection) layers.push(p.injection)
  if (p.skills) layers.push(p.skills)
  if (p.role) {
    layers.push(SCOPE_NOTE)
    layers.push(p.role)
  }
  if (p.suffix) layers.push(p.suffix)
  return layers.join("\n\n")
}
