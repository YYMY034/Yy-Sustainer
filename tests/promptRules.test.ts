test("基础层每条硬规则都有锚点钉住（瘦身不许删规则）", () => {
  const missing = RULES.filter(([, anchor]) => {
    // 锚点里 "|" 是「任一命中」的分隔（规则有多种措辞时）
    const alts = anchor.split("|")
    return !alts.some((a) => SYSTEM_PROMPT.includes(a))
  })
  assert.equal(missing.length, 0,
    `这些规则的锚点不在 SYSTEM_PROMPT 里——要么规则被删了（瘦身过头），要么措辞变了（来本文件更新锚点）：\n` +
    missing.map(([g, a, why]) => `  [${g}] ${a}（防：${why}）`).join("\n"))
})

test("锚点表自身没有漂移（重复/空/未说明防什么）", () => {
  const seen = new Set<string>()
  for (const [group, anchor, why] of RULES) {
    assert.ok(group && anchor && why, `锚点三要素要全：${group}/${anchor}/${why}`)
    assert.ok(!seen.has(anchor), `锚点重复：${anchor}`)
    seen.add(anchor)
    assert.ok(why.length >= 4, `「防什么」要写具体（写理由的过程就是审查）：${anchor}`)
  }
})

test("基础层仍保留 T91 分层依赖的结构（精简层对比的前提）", () => {
  // check-t91 断言过这两条，这里从「规则守卫」角度再钉一遍：
  // 工具全景节是模型理解自身能力面的入口，瘦身不能并掉
  assert.ok(SYSTEM_PROMPT.includes("## 工具全景"), "工具全景节没了——模型不再知道自己有什么工具")
  assert.ok(SYSTEM_PROMPT.includes("## 身份"), "身份节没了")
  // 精简层必须明显更小（否则 compactBase 失去意义）
  assert.ok(SYSTEM_PROMPT.length > 8000, `基础层只剩 ${SYSTEM_PROMPT.length} 字符——瘦身瘦成了精简层？`)
})
